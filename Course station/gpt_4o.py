def extract_randomized_questions_from_book(book_data, n=50):
    questions = []
    for chapter in book_data.get('chapters', []):
        content = chapter.get('content', '')
        title = chapter.get('title', '')
        sentences = [s.strip() for s in content.split('\n') if len(s.strip()) > 30]
        for s in sentences:
            if random.random() < 0.2:
                questions.append({
                    'type': 'general',
                    'topic': title,
                    'question': f'What is the meaning of: "{s[:60]}..."?',
                    'answer': s,
                    'explanation': f'This is a direct excerpt from the chapter: {title}.'
                })
    random.shuffle(questions)
    return questions[:n] if questions else []

