def cosine_similarity(a, b):
    a = np.array(a)
    b = np.array(b)
    return np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b))

def retrieve_relevant_chunks_by_topic(topic, kb, corpus, corpus_embeddings, top_k=3):
    # Embed the topic string as the query
    query_embedding = embed_texts_batched([topic])[0]
    # Compute similarity to all corpus entries
    sims = [cosine_similarity(query_embedding, emb) for emb in corpus_embeddings]
    # Get indices of top_k matches
    top_indices = np.argsort(sims)[-top_k:][::-1]
    return [kb[i] for i in top_indices]

def get_synonyms(word):
    synonyms = set()
    for syn in wordnet.synsets(word):
        for lemma in syn.lemmas():
            synonyms.add(lemma.name())
    return synonyms

def normalize_text(text):
    # Lowercase, strip, remove punctuation, remove stopwords, stem, and expand synonyms
    text = text.strip().lower().translate(str.maketrans('', '', string.punctuation))
    tokens = nltk.word_tokenize(text)
    stop_words = set(stopwords.words('english'))
    ps = PorterStemmer()
    filtered = [ps.stem(w) for w in tokens if w not in stop_words]
    # Expand with synonyms
    expanded = set(filtered)
    for w in filtered:
        expanded.update([ps.stem(s) for s in get_synonyms(w)])
    return ' '.join(expanded)

def semantic_similarity(a, b):
    try:
        response = openai.embeddings.create(
            input=[a, b],
            model="text-embedding-3-small"
        )
        emb_a = response.data[0].embedding
        emb_b = response.data[1].embedding
        a = np.array(emb_a)
        b = np.array(emb_b)
        return np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b))
    except Exception as e:
        print(f"Semantic similarity error: {e}")
        return 0.0

def ast_equal(code1, code2):
    try:
        tree1 = ast.parse(code1)
        tree2 = ast.parse(code2)
        return ast.dump(tree1) == ast.dump(tree2)
    except Exception as e:
        print(f"[DEBUG] AST comparison error: {e}")
        return False

def safe_exec(code):
    """Executes code and returns stdout output as string."""
    try:
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            exec(code, {})
        return output.getvalue().strip()
    except Exception as e:
        return str(e)

def extract_keywords(text):
    # Lowercase, remove punctuation, tokenize, remove stopwords, stem
    text = text.strip().lower().translate(str.maketrans('', '', string.punctuation))
    tokens = nltk.word_tokenize(text)
    stop_words = set(stopwords.words('english'))
    ps = PorterStemmer()
    keywords = set(ps.stem(w) for w in tokens if w not in stop_words)
    return keywords

def is_coding_answer_correct(user_code, correct_code, threshold=85, semantic_threshold=0.70):
    user_output = safe_exec(user_code)
    correct_output = safe_exec(correct_code)
    if user_output and correct_output:
        user_output_norm = normalize_text(user_output)
        correct_output_norm = normalize_text(correct_output)
        fuzzy_score = fuzz.ratio(user_output_norm, correct_output_norm)
        sem_score = semantic_similarity(user_output_norm, correct_output_norm)
        diff_score = difflib.SequenceMatcher(None, user_output_norm, correct_output_norm).ratio()
        ast_score = ast_equal(user_output, correct_output)
        print(f"[DEBUG] Coding output fuzzy score: {fuzzy_score}, semantic similarity: {sem_score}, difflib: {diff_score}, AST equal: {ast_score}")
        if fuzzy_score >= threshold or sem_score >= semantic_threshold or diff_score >= 0.75 or ast_score:
            return True
        return False
    # Fallback to code similarity
    user_code_norm = normalize_text(user_code)
    correct_code_norm = normalize_text(correct_code)
    fuzzy_score = fuzz.ratio(user_code_norm, correct_code_norm)
    sem_score = semantic_similarity(user_code_norm, correct_code_norm)
    diff_score = difflib.SequenceMatcher(None, user_code_norm, correct_code_norm).ratio()
    ast_score = ast_equal(user_code, correct_code)
    print(f"[DEBUG] Coding code fuzzy score: {fuzzy_score}, semantic similarity: {sem_score}, difflib: {diff_score}, AST equal: {ast_score}")
    if fuzzy_score >= threshold or sem_score >= semantic_threshold or diff_score >= 0.75 or ast_score:
        return True
    return False

