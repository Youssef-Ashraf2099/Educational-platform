def generate_auto_question(prompt, max_tokens=256):
    print(f"[DEBUG] Generating question with prompt:\n{prompt}\n---")
    response = openai.chat.completions.create(
        model="gpt-4o",
        messages=[
            {"role": "system", "content": "You are a helpful question generation assistant for data structures exams."},
            {"role": "user", "content": prompt}
        ],
        max_tokens=max_tokens,
        temperature=0.7
    )
    result = response.choices[0].message.content.strip()
    print(f"[DEBUG] Generated question:\n{result}\n=====")
    return result

def generate_unique_questions(topic, question_type, n, kb, corpus, corpus_embeddings, max_tokens=256, difficulty=None):
    used_chunks = set()
    questions = []
    attempts = 0

    while len(questions) < n and attempts < n*3:
        relevant_chunks = retrieve_relevant_chunks_by_topic(topic, kb, corpus, corpus_embeddings, top_k=5)
        random.shuffle(relevant_chunks)
        for chunk in relevant_chunks:
            chunk_str = chunk_to_string(chunk)
            if chunk_str in used_chunks:
                continue
            used_chunks.add(chunk_str)
            if question_type == "mcq":
                prompt = make_mcq_question_prompt(topic, chunk_str, difficulty)
            elif question_type == "coding":
                prompt = make_coding_question_prompt(topic, chunk_str, difficulty)
            elif question_type == "tf":
                prompt = make_tf_question_prompt(topic, chunk_str, difficulty)
            else:
                prompt = make_general_question_prompt(topic, chunk_str, difficulty)
            q = generate_auto_question(prompt, max_tokens=max_tokens)
            question_text = q.split('\n')[0].strip().lower()
            if all(question_text not in x.lower() for x in questions):
                questions.append(q)
                break
        attempts += 1
    return questions

